/**
 * Generation requests: what was written, for whom, on which day -- and any of
 * it written again.
 *
 * A request keeps no generated data. It keeps its seed, the pattern and what
 * each file was written through, so writing a file again makes the same file;
 * its fingerprint says whether it did, and the SDM build says why not. A
 * database load is regenerated as evidence: its rows as CSV, written nowhere.
 */

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { Banner, Button, Chip, Empty } from "../components/primitives";
import { failure } from "../components/GenerateFileMenu";
import { useAppActions } from "../lib/appActions";
import {
  ApiError,
  api,
  type FilePattern,
  type GenerationRequest,
  type GenerationRequestFile,
  type GenerationRequestsPayload,
} from "../lib/api";
import { keyOf } from "../lib/pack";

export function GenerationRequests({
  onUse, focus = null,
}: {
  onUse: (chosen: FilePattern) => void;
  /** A run to bring into view: the one a confirmation named. */
  focus?: number | null;
}) {
  const [day, setDay] = useState("");
  const [patternId, setPatternId] = useState("");
  const [user, setUser] = useState("");
  const [payload, setPayload] = useState<GenerationRequestsPayload | null>(null);
  // Every pattern and person seen, so a filter's choices stay while it is set.
  const [seen, setSeen] = useState<{ patterns: Map<number, string>; users: Set<string> }>(
    () => ({ patterns: new Map(), users: new Set() }),
  );
  const [busy, setBusy] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);
  const { notify } = useAppActions();
  // Each load is numbered; only the latest one's answer is shown, so a slow
  // answer for filters that have since changed never replaces a newer one.
  const loads = useRef(0);

  const load = useCallback(async () => {
    const mine = ++loads.current;
    setError(null);
    try {
      const loaded = await api.generationRequests({
        ...(day ? { day } : {}),
        ...(patternId ? { pattern_id: Number(patternId) } : {}),
        ...(user ? { user } : {}),
      });
      if (mine !== loads.current) return;
      setPayload(loaded);
      setSeen((before) => {
        const patterns = new Map(before.patterns);
        const users = new Set(before.users);
        for (const r of loaded.requests) {
          if (r.pattern_id != null) patterns.set(r.pattern_id, r.pattern_name ?? `Pattern ${r.pattern_id}`);
          if (r.created_by) users.add(r.created_by);
        }
        return { patterns, users };
      });
    } catch (e) {
      if (mine !== loads.current) return;
      setError(e instanceof ApiError ? e.message : String(e));
    }
  }, [day, patternId, user]);
  const filtered = Boolean(day || patternId || user);
  const patternChoices = useMemo(
    () => [...seen.patterns].sort((a, b) => a[1].localeCompare(b[1])),
    [seen],
  );

  useEffect(() => {
    void load();
  }, [load]);

  useEffect(() => {
    if (focus === null || !payload) return;
    document.getElementById(`run-${focus}`)?.scrollIntoView({ block: "center" });
  }, [focus, payload]);

  // A Rerun that fails is said as an alert that stays until it is dismissed,
  // wherever the page is scrolled to.
  const again = useCallback(
    async (file: GenerationRequestFile) => {
      if (busy !== null) return;
      setBusy(file.id);
      try {
        await api.generationFileAgain(file.id, file.file_name);
        await load();
      } catch (e) {
        notify({ tone: "alarm", message: failure(e) });
      } finally {
        setBusy(null);
      }
    },
    [load, notify, busy],
  );

  return (
    <section className="panel requests">
      {error && <Banner tone="alarm">{error}</Banner>}
      <div className="panel__actions">
        <label className="named">
          <span>Generated on</span>
          <input type="date" value={day} onChange={(e) => setDay(e.target.value)} />
        </label>
        <label className="named">
          <span>Generated from pattern</span>
          <select value={patternId} onChange={(e) => setPatternId(e.target.value)}>
            <option value="">All patterns</option>
            {patternChoices.map(([id, name]) => (
              <option key={id} value={String(id)}>
                {name}
              </option>
            ))}
          </select>
        </label>
        <label className="named">
          <span>Generated by</span>
          <select value={user} onChange={(e) => setUser(e.target.value)}>
            <option value="">All users</option>
            {[...seen.users].sort().map((u) => (
              <option key={u} value={u}>
                {u}
              </option>
            ))}
          </select>
        </label>
        {filtered && (
          <Button
            onClick={() => {
              setDay("");
              setPatternId("");
              setUser("");
            }}
          >
            Clear filters
          </Button>
        )}
      </div>

      {payload === null ? null : payload.requests.length === 0 ? (
        <Empty title="No runs yet">
          {filtered
            ? "No runs match the selected filters."
            : "Generate a file from a pattern on any tab to record a run."}
        </Empty>
      ) : (
        payload.requests.map((request) => (
          <RequestCard
            key={request.id}
            request={request}
            build={payload.build}
            busy={busy}
            onAgain={again}
            onUse={onUse}
            focused={request.id === focus}
          />
        ))
      )}
    </section>
  );
}

function RequestCard({
  request, build, busy, onAgain, onUse, focused,
}: {
  request: GenerationRequest;
  build: string;
  busy: number | null;
  onAgain: (file: GenerationRequestFile) => void;
  onUse: (chosen: FilePattern) => void;
  focused: boolean;
}) {
  const originals = request.files.filter((f) => f.replay_of === null);
  const latest = (file: GenerationRequestFile) =>
    request.files.filter((f) => f.replay_of === file.id).at(-1) ?? null;

  return (
    <article
      id={`run-${request.id}`}
      className={"requests__card" + (focused ? " requests__card--focus" : "")}
    >
      <header className="requests__head">
        <h3>
          Run {request.id} <span className="requests__for">{request.pattern_name}</span>
        </h3>
        <span className="panel__hint">
          Started {new Date(request.started).toLocaleString()}
          {request.created_by ? ` by ${request.created_by}` : ""} · Seed{" "}
          <span className="mono">{request.seed}</span>
        </span>
        {request.pattern_key !== "plan" && request.subject !== "load" && (
          <Button onClick={() => onUse(asFilePattern(request))}>
            Generate other format
          </Button>
        )}
      </header>
      <div className="requests__files">
      <table className="panel__table">
        <thead>
          <tr>
            <th>File</th>
            <th>Generated</th>
            <th className="right">Size</th>
            <th>Checksum</th>
            <th>Rerun</th>
            <th />
          </tr>
        </thead>
        <tbody>
          {originals.map((file) => {
            const replay = latest(file);
            const load = file.format === "database";
            return (
              <tr key={file.id}>
                <td>
                  {load ? `Loaded into ${file.target ?? "target"}` : file.file_name}
                  <span className="panel__by"> {formatName(file.format)}</span>
                </td>
                <td>
                  {new Date(file.written_at).toLocaleString()}
                  {file.written_by ? ` by ${file.written_by}` : ""}
                </td>
                <td className="right num">
                  {load ? `${(file.rows ?? 0).toLocaleString()} rows` : size(file.bytes)}
                </td>
                <td className="mono">{file.fingerprint.slice(0, 12)}</td>
                <td>
                  {file.rerunnable === false ? (
                    // Said in the row, not only on hover: the reason Rerun is off.
                    <span className="requests__refusal" id={`rerun-refusal-${file.id}`}>
                      {file.rerun_refusal ?? "This run can't be rerun."}
                    </span>
                  ) : replay === null ? (
                    file.sdm_build && file.sdm_build !== build ? (
                      <Chip tone="caution">Generated by an earlier SDM build</Chip>
                    ) : (
                      <span className="panel__hint">Not rerun</span>
                    )
                  ) : replay.matched ? (
                    <Chip tone="affirm">{load ? "Identical rows" : "Identical file"}</Chip>
                  ) : (
                    <Chip tone="alarm">
                      {replay.sdm_build !== file.sdm_build
                        ? "Differs: SDM build changed"
                        : replay.changed?.length
                          ? `Differs: ${replay.changed.join(" and ")} changed`
                          : "Differs: source data changed"}
                    </Chip>
                  )}
                </td>
                <td className="right">
                  {/* Unavailable when the run can't be rerun (the reason is in
                      the row and describes the button) or while another Rerun
                      works; busy, it keeps focus. */}
                  <Button
                    onClick={() => onAgain(file)}
                    busy={busy === file.id}
                    disabled={file.rerunnable === false || (busy !== null && busy !== file.id)}
                    describedBy={file.rerunnable === false ? `rerun-refusal-${file.id}` : undefined}
                    keepFocus
                  >
                    Rerun
                  </Button>
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
      </div>
    </article>
  );
}

/** A recorded file format as a person reads it. */
function formatName(format: string): string {
  const names: Record<string, string> = {
    csv: "Delimited", fixed: "Fixed width", database: "Database load",
    x12: "X12", edi834: "X12 834", edi837: "X12 837", fhir: "FHIR", hl7v2: "HL7 v2",
    cda: "HL7 v3",
  };
  if (format.startsWith("edi:")) return "X12";
  // A standard file written from a pattern's Generate file.
  if (format.startsWith("standard:fhir")) return "FHIR";
  if (format.startsWith("standard:hl7v3") || format.startsWith("standard:cda")) return "HL7 v3";
  if (format.startsWith("standard:hl7")) return "HL7 v2";
  // Modeled on a sample: a saved configuration, or one accepted and not saved.
  if (format.startsWith("sample:") || format.startsWith("unsaved:")) return "Custom format";
  return names[format] ?? format;
}

function size(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

/** An earlier request, as what files are written for. */
export function asFilePattern(request: GenerationRequest): FilePattern {
  return {
    kind: "request",
    requestId: request.id,
    name: `Run ${request.id} · ${request.pattern_name ?? "Unnamed pattern"}`,
    entity: request.of ?? keyOf("primary"),
    members: request.members ?? 100,
    started: request.started,
  };
}
